    public let checkId: UUID
    public let faceValue: Double
    public let dueDate: String
    public let daysToMaturity: Int
    public let monthlyRate: Double
    public let discountRate: Double
    public let grossDiscount: Double
    public let commissionAmount: Double
    public let netPresentValue: Double
    public let effectiveAnnualYield: Double
    
    public init(
        checkId: UUID,
        faceValue: Double,
        dueDate: String,
        daysToMaturity: Int,
        monthlyRate: Double,
        discountRate: Double,
        grossDiscount: Double,
        commissionAmount: Double,
        netPresentValue: Double,
        effectiveAnnualYield: Double
    ) {
        self.checkId = checkId
        self.faceValue = faceValue
        self.dueDate = dueDate
        self.daysToMaturity = daysToMaturity
        self.monthlyRate = monthlyRate
        self.discountRate = discountRate
        self.grossDiscount = grossDiscount
        self.commissionAmount = commissionAmount
        self.netPresentValue = netPresentValue
        self.effectiveAnnualYield = effectiveAnnualYield
    }
}

