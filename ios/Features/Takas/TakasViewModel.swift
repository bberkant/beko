// MARK: - Takas Service Protocol

/// Protocol defining backend data requirements for Takas Çekleri Portföyü.
public protocol TakasServiceProtocol: Sendable {
    func fetchChecks(type: CheckType?, status: CheckStatus?, limit: Int, offset: Int) async throws -> [EBSCheck]
}

extension SupabaseService: TakasServiceProtocol {}

// MARK: - Primary Segment Selector

/// Dual segment matching Kuveyt Türk prototype: Takasta vs. İç Takas vs. Ödenen.
public enum TakasSegment: String, CaseIterable, Identifiable, Sendable {
    case takasta = "Takasta"
    case icTakas = "İç Takas"
    case odenen = "Ödenen"
    
    public var id: String { rawValue }
    public var title: String { rawValue }
}

// MARK: - Cheque Status Filter Pills

/// Status filter pills matching Kuveyt Türk design tokens and database enum values.
public enum TakasStatusFilter: String, CaseIterable, Identifiable, Sendable {
    case all = "Tümü"
    case portfoyde = "Portföyde"
    case tahsilde = "Tahsilde"
    case teminatta = "Teminata Verildi"
    case odendi = "Ödendi"
    
    public var id: String { rawValue }
    
    public var targetStatus: CheckStatus? {
        switch self {
        case .all: return nil
        case .portfoyde: return .portfoyde
        case .tahsilde: return .tahsilde
        case .teminatta: return .teminataVerildi
        case .odendi: return .odendi
        }
    }
}

// MARK: - Date Preset Filter

/// Quick date filters for clearing schedules.
public enum TakasDatePreset: String, CaseIterable, Identifiable, Sendable {
    case all = "Tüm Vadeler"
    case today = "Bugün"
    case thisWeek = "Bu Hafta"
    case thisMonth = "Bu Ay"
    case overdue = "Vadesi Geçenler"
    
    public var id: String { rawValue }
}

// MARK: - Bank Concentration Metric

/// Aggregated quota and concentration share per clearing bank.
public struct TakasBankMetric: Identifiable, Equatable, Sendable {
    public var id: String { bankName }
    public let bankName: String
    public let totalAmount: Double
    public let checkCount: Int
    public let concentrationPercentage: Double
    
    public init(bankName: String, totalAmount: Double, checkCount: Int, concentrationPercentage: Double) {
        self.bankName = bankName
        self.totalAmount = totalAmount
        self.checkCount = checkCount
        self.concentrationPercentage = concentrationPercentage
    }
}

// MARK: - Valuation & Discounting Result

