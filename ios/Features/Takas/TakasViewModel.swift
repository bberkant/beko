    }
    
    // MARK: - Date Helpers
    
    private func parseDate(_ dateStr: String) -> Date? {
        let clean = dateStr.components(separatedBy: "T").first ?? dateStr
        
        let isoFormatter = DateFormatter()
        isoFormatter.dateFormat = "yyyy-MM-dd"
        if let d = isoFormatter.date(from: clean) { return d }
        
        let trFormatter = DateFormatter()
        trFormatter.dateFormat = "dd.MM.yyyy"
        return trFormatter.date(from: clean)
    }
    
    public func formatDate(_ dateStr: String) -> String {
        let clean = dateStr.components(separatedBy: "T").first ?? dateStr
        let parts = clean.split(separator: "-")
        if parts.count == 3 {
            return "\(parts[2]).\(parts[1]).\(parts[0])"
        }
        return dateStr
    }
    
    public func daysBetween(_ start: Date, _ end: Date) -> Int {
        let startDay = calendar.startOfDay(for: start)
        let endDay = calendar.startOfDay(for: end)
        return calendar.dateComponents([.day], from: startDay, to: endDay).day ?? 0
    }
    
    public func daysRemainingBadge(for dueDateStr: String) -> (text: String, isOverdue: Bool) {
        guard let due = parseDate(dueDateStr) else { return ("—", false) }
        let diff = daysBetween(Date(), due)
        if diff < 0 {
            return ("\(abs(diff)) Gün Geçti", true)
        } else if diff == 0 {
            return ("Bugün", false)
        } else {
            return ("\(diff) Gün Kaldı", false)
        }
    }
